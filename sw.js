// Offline-Modus für Denkspaß.
// Die App-Dateien werden auf dem Gerät gespeichert. Mit Internet wird immer
// zuerst die neueste Version geladen, ohne Internet die gespeicherte.
// Bei größeren Änderungen VERSION hochzählen, dann wird der alte Speicher aufgeräumt.
const VERSION = 'denkspass-v1';
const FONTS = 'denkspass-fonts';
const FILES = ['./', 'index.html', 'manifest.json', 'icon-192.png', 'icon-512.png', 'apple-touch-icon.png'];

self.addEventListener('install', e => {
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k !== VERSION && k !== FONTS).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);

  // Schriften von Google: einmal laden, danach vom Gerät nehmen.
  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    e.respondWith(
      caches.open(FONTS).then(c => c.match(req).then(hit => hit || fetch(req).then(res => { c.put(req, res.clone()); return res; })))
    );
    return;
  }

  if (url.origin !== self.location.origin) return;

  // Eigene Dateien: zuerst aus dem Netz (neueste Version), sonst vom Gerät.
  e.respondWith(
    fetch(req)
      .then(res => {
        if (res.ok) { const copy = res.clone(); caches.open(VERSION).then(c => c.put(req, copy)); }
        return res;
      })
      .catch(() => caches.match(req).then(hit => hit || caches.match('index.html')))
  );
});
